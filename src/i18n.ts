export const isRtlLanguage = (language: Language): boolean => language === 'fa' || language === 'ar'
export const translate = (language: Language, key: TranslationKey): string => dictionaries[language][key]
export const localized = (language: Language, text: LocalizedText): string => {
  const direct = text[language]
  if (direct) return direct
  if (language === 'en' || language === 'fa') return text.en
  return exerciseTextTranslations[language][text.en] ?? text.en
}
